#!/usr/bin/env python3
"""The paper's data tables, generated from the collected data.

    python3 Paper/scripts/make_tables.py

Writes `Paper/tables/*.tex`, each a complete `tabular` environment that
`paper.tex` drops into a `table` float with `\\input`.  The tables are generated
rather than typed because a number transcribed by hand into a LaTeX source is a
number nobody can recompute, which is the rule the protocol sets for the whole
study.

Each file carries the whole `tabular` rather than only its rows: under current
LaTeX, `\\input` inside an open alignment breaks it, and the rows would have to
be pasted by hand to work around that -- which is the thing this script exists
to avoid.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paperdata as D

TABLES = D.PAPER / "tables"
SLOW = D.SLOW_RESPONDERS
BANNER = ("%% generated by Paper/scripts/make_tables.py from "
          "Study/data/runs.ndjson -- do not edit\n")


def write(name: str, size: str, colspec: str, header: list[str], body: list[str],
          tabcolsep: str | None = None) -> None:
    out = [BANNER, f"\\{size}\n"]
    if tabcolsep:
        out.append(f"\\setlength{{\\tabcolsep}}{{{tabcolsep}}}\n")
    out.append(f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n")
    out += [line + "\n" for line in header]
    out.append("\\midrule\n")
    out += [line + "\n" for line in body]
    out.append("\\bottomrule\n\\end{tabular}\n")
    (TABLES / f"{name}.tex").write_text("".join(out))
    print(f"  {name}.tex")


def seconds(value: float) -> str:
    if value >= 100:
        return f"{value:,.1f}"
    if value >= 10:
        return f"{value:.2f}"
    return f"{value:.3f}"


def tex(condition: str) -> str:
    return f"\\texttt{{{D.SHORT[condition]}}}"


def table_conditions(runs) -> None:
    body = []
    for condition in D.ALL_CONDITIONS:
        cells = [tex(condition)]
        for cache_state in ("warm", "cold"):
            sample = [r for r in runs if r.condition_id == condition
                      and r.cache_state == cache_state]
            times = [r.wall_clock for r in sample]
            cells.append(str(len(sample)))
            cells.append(
                f"{seconds(D.median(times))}\\,"
                f"{{\\tiny[{seconds(D.quantile(times, 0.25))}--"
                f"{seconds(D.quantile(times, 0.75))}]}}")
            cells.append(f"{D.median([r.recall for r in sample]):.2f}")
        body.append(" & ".join(cells) + " \\\\")
    write("tab_conditions", "scriptsize", "@{}lrlcrlc@{}",
          [r"& \multicolumn{3}{c}{warm arm} & \multicolumn{3}{c}{cold arm}\\",
           r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
           r"condition & $n$ & median (s) & rec. & $n$ & median (s) & rec.\\"],
          body, tabcolsep="2.6pt")


def table_budget(runs) -> None:
    body = []
    for condition in ("ns.fixed.timeout", "ns.disc.unpriv", "ns.naming.full",
                      "ns.budget.shared"):
        for cache_state in ("warm", "cold"):
            sample = [r for r in runs if r.condition_id == condition
                      and r.cache_state == cache_state]
            wire = sample[0].raw["capture"]["wire"]
            body.append(" & ".join([
                tex(condition) if cache_state == "warm" else "",
                cache_state,
                str(len(sample)),
                f"{D.median([r.raw['parse']['discovery']['elapsed_millis'] for r in sample]):,.0f}",
                f"{D.median([r.raw['capture']['wire']['icmp_echo_replies'] for r in sample]):.0f}",
                f"{D.median([r.raw['capture']['wire']['arp_replies'] for r in sample]):.0f}",
                f"{D.median([r.replies_seen for r in sample]):.0f}",
                f"{D.median([r.hosts_found for r in sample]):.0f}",
                f"{sum(len([a for a in SLOW if a in r.found]) for r in sample) / len(sample):.2f}",
                f"{D.median([r.recall for r in sample]):.2f}",
            ]) + " \\\\")
        body.append("\\addlinespace[1.5pt]")
    write("tab_budget", "scriptsize", "@{}llrrrrrrrr@{}",
          [r"condition & arm & $n$ & stage & echo & ARP & attr. & rep. & slow "
           r"& rec.\\",
           r" & & & (ms) & wire & repl. & & & /2 &\\"],
          body[:-1], tabcolsep="2.6pt")


def table_cold_n(runs) -> None:
    counts = sorted((len([r for r in runs if r.condition_id == c
                          and r.cache_state == "cold"]), c)
                    for c in D.ALL_CONDITIONS)
    left, right = counts[:7], counts[7:]
    body = []
    for index in range(7):
        row = [tex(left[index][1]), str(left[index][0])]
        row += ([tex(right[index][1]), str(right[index][0])]
                if index < len(right) else ["", ""])
        body.append(" & ".join(row) + " \\\\")
    write("tab_cold_n", "footnotesize", "@{}lrlr@{}",
          [r"condition & cold $n$ & condition & cold $n$\\"], body)


def table_precision(runs) -> None:
    """Precision, median found-set size and recall, warm arm.

    Not placed in the current draft: the paper is at the top of its page budget
    and the four numbers that matter are in the prose beside Table II.  It is
    generated anyway, because a designer cutting the paper down cannot re-add a
    table that was never built.
    """
    body = []
    for condition in D.ALL_CONDITIONS:
        warm = [r for r in runs if r.condition_id == condition
                and r.cache_state == "warm"]
        body.append(" & ".join([
            tex(condition),
            f"{D.median([len(r.found) for r in warm]):.0f}",
            f"{D.median([r.recall for r in warm]):.2f}",
            f"{D.median([r.precision for r in warm]):.3f}",
        ]) + " \\\\")
    write("tab_precision", "footnotesize", "@{}lrrr@{}",
          [r"condition & addresses & recall & precision\\"], body)


def main() -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    runs = D.runs()
    print(f"{len(runs)} admissible runs -> {TABLES}")
    table_conditions(runs)
    table_budget(runs)
    table_cold_n(runs)
    table_precision(runs)


if __name__ == "__main__":
    main()
